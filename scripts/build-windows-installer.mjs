// Builds Prism-Mapper-v<version>-Windows-x64-Setup.exe with Inno Setup 6.
//
// Run scripts/package-release.mjs first: the installer packs the same staged
// Windows build that becomes the portable ZIP, so both contain identical files.
//
//   node scripts/build-windows-installer.mjs
//
// Inno Setup is a free Windows program (https://jrsoftware.org/isinfo.php; the
// GitHub Windows runners have it preinstalled). ISCC_PATH can name ISCC.exe
// when it is somewhere unusual.
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import { mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { releaseName } from "./package-release.mjs";
import { copyrightLine, numericVersion } from "./windows-exe.mjs";
import {
  installerSigningCommand,
  requireSignedRelease,
  verifyWindowsApplication,
  verifyWindowsFile,
  windowsSigningEnabled,
} from "./sign-windows.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export function installerFileName(version) {
  return `${releaseName(version, "win32", "x64")}-Setup.exe`;
}

// Inno Setup's preprocessor reads "text" as a string; a double quote inside is
// written twice.
const literal = (value) => `"${String(value).replaceAll('"', '""')}"`;

// The values scripts/windows-installer.iss asks for. They are written into a
// copy of the script as #define lines rather than passed as /D options, so the
// file the compiler reads is complete and there are no command-line quoting
// rules to get wrong for paths with spaces.
export function installerDefines({
  version,
  copyright,
  repository,
  stage,
  license,
  output,
}) {
  return [
    ["AppVersion", version],
    ["AppNumericVersion", numericVersion(version)],
    ["AppCopyright", copyright],
    ["RepoDir", repository],
    ["StageDir", stage],
    ["LicenseFile", license],
    ["OutputDir", output],
  ];
}

export const withWindowsLineEndings = (text) => text.replace(/\r?\n/g, "\r\n");

export const generatedHeaderComment =
  "; Generated by scripts/build-windows-installer.mjs from scripts/windows-installer.iss. Do not edit.";

export function installerScript(template, defines, { signed = false } = {}) {
  const header = [
    generatedHeaderComment,
    ...defines.map(([name, value]) => `#define ${name} ${literal(value)}`),
    ...(signed ? ["#define SignedBuild"] : []),
    "",
  ];
  return `${header.join("\r\n")}\r\n${withWindowsLineEndings(template)}`;
}

export function installerCompilerArguments(script, { signed = false } = {}) {
  return [
    "/Qp",
    ...(signed ? [`/SPrismSigning=${installerSigningCommand()}`] : []),
    script,
  ];
}

// Where Inno Setup 6 puts ISCC.exe, most specific first.
export function compilerCandidates(env = process.env) {
  const candidates = [];
  if (env.ISCC_PATH) candidates.push(env.ISCC_PATH);
  for (const base of [
    env["ProgramFiles(x86)"],
    env.ProgramFiles,
    env.LOCALAPPDATA && path.win32.join(env.LOCALAPPDATA, "Programs"),
  ])
    if (base)
      candidates.push(path.win32.join(base, "Inno Setup 6", "ISCC.exe"));
  return candidates;
}

export function findCompiler(
  env = process.env,
  { exists = existsSync, which = whichOnPath } = {},
) {
  for (const candidate of compilerCandidates(env))
    if (exists(candidate)) return candidate;
  return which("ISCC.exe");
}

function whichOnPath(name) {
  try {
    return (
      execFileSync("where.exe", [name], { encoding: "utf8" })
        .split(/\r?\n/)
        .find(Boolean) || null
    );
  } catch {
    return null;
  }
}

export async function buildInstaller({
  output = path.join(root, "release", "distribution"),
  compiler = findCompiler(),
  env = process.env,
  run = execFileSync,
  verifyApplication = (application) =>
    verifyWindowsApplication(application, { run }),
  verifyFile = (filename) => verifyWindowsFile(filename, { run }),
} = {}) {
  const signed = windowsSigningEnabled(env);
  if (requireSignedRelease(env) && !signed)
    throw new Error(
      "A published Windows installer requires Artifact Signing. Configure signing or use a dry run.",
    );
  const pkg = JSON.parse(
    await readFile(path.join(root, "package.json"), "utf8"),
  );
  const folder = releaseName(pkg.version, "win32", "x64");
  const staging = path.join(output, pkg.version, "win32-x64");
  const stage = path.join(staging, folder);
  for (const required of [
    "Prism Mapper/Prism Mapper.exe",
    "Example projects",
    "LICENSE",
    "THIRD_PARTY_NOTICES.md",
    "ELECTRON-LICENSE.txt",
  ])
    if (!(await stat(path.join(stage, required)).catch(() => null)))
      throw new Error(
        `${required} is missing from ${stage}. Run node scripts/package-release.mjs first.`,
      );
  if (!compiler)
    throw new Error(
      "Inno Setup 6 was not found. Install it (winget install JRSoftware.InnoSetup, or choco install innosetup) or set ISCC_PATH to ISCC.exe.",
    );
  if (signed) await verifyApplication(path.join(stage, "Prism Mapper"));

  const license = await readFile(path.join(root, "LICENSE"), "utf8");
  const generated = path.join(staging, "installer");
  await rm(generated, { recursive: true, force: true });
  await mkdir(generated, { recursive: true });
  const licenseFile = path.join(generated, "LICENSE.txt");
  await writeFile(licenseFile, withWindowsLineEndings(license));
  const script = path.join(generated, "windows-installer.iss");
  await writeFile(
    script,
    installerScript(
      await readFile(
        path.join(root, "scripts", "windows-installer.iss"),
        "utf8",
      ),
      installerDefines({
        version: pkg.version,
        copyright: copyrightLine(license),
        repository: root,
        stage,
        license: licenseFile,
        output,
      }),
      { signed },
    ),
  );

  const name = installerFileName(pkg.version);
  const target = path.join(output, name);
  await rm(target, { force: true });
  await rm(`${target}.sha256`, { force: true });
  // /Qp: print progress and errors, not every file name.
  run(compiler, installerCompilerArguments(script, { signed }), {
    stdio: "inherit",
  });

  const size = (await stat(target).catch(() => null))?.size;
  if (!size) throw new Error(`Inno Setup did not write ${target}`);
  // The runtime alone is far larger than this; a tiny file means the packing
  // step found nothing to pack.
  if (size < 20 * 1024 * 1024)
    throw new Error(`${name} is only ${size} bytes, which is too small`);
  if (signed) await verifyFile(target);
  const checksum = createHash("sha256")
    .update(await readFile(target))
    .digest("hex");
  await writeFile(`${target}.sha256`, `${checksum}  ${name}\n`);
  console.log(
    `Built installer:\n${target}\n${size} bytes\nSHA-256: ${checksum}`,
  );
  return { installer: target, checksum, size, script };
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
)
  await buildInstaller();
